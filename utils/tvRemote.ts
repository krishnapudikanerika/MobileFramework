export async function pressRight(driver:any){

    await driver.pressKeyCode(22);

}

export async function pressLeft(driver:any){

    await driver.pressKeyCode(21);

}

export async function pressDown(driver:any){

    await driver.pressKeyCode(20);

}

export async function pressUp(driver:any){

    await driver.pressKeyCode(19);

}

export async function pressOk(driver:any){

    await driver.pressKeyCode(23);

}